"""Sweep over results/eval/*.json and results/filtered_summaries to build the
two main tables (Table 1 main result, Table 2 random vs structured).

Each evaluate_model.py output is named:
    results/eval/<corruption>_eta<XX>_<method>.json

Each consensus_filter.py summary is named:
    data/filtered/hh_train_<corruption>_eta<XX>/filter_summary.json

Usage:
    python -m src.aggregate_results --out_dir results/tables
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


PAT = re.compile(r"^(?P<corr>[a-z_]+)_eta(?P<eta>\d{1,3})_(?P<method>[a-z0-9_]+)\.json$")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--eval_dir", default=str(ROOT / "results" / "eval"))
    ap.add_argument("--filtered_root", default=str(ROOT / "data" / "filtered"))
    ap.add_argument("--out_dir", default=str(ROOT / "results" / "tables"))
    args = ap.parse_args()

    eval_dir = Path(args.eval_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    for jf in sorted(eval_dir.glob("*.json")):
        m = PAT.match(jf.name)
        if not m:
            continue
        corr = m.group("corr")
        eta = int(m.group("eta"))
        method = m.group("method")
        d = json.loads(jf.read_text())
        # Filter summary if it exists
        filt = (
            Path(args.filtered_root)
            / f"hh_train_{corr}_eta{eta}"
            / "filter_summary.json"
        )
        filt_data = json.loads(filt.read_text()) if filt.exists() else {}
        m_filter = filt_data.get(method, {}) if filt_data else {}

        rows.append(
            {
                "corruption": corr,
                "eta": eta,
                "method": method,
                "preference_acc": d["preference"]["preference_acc"],
                "mean_margin": d["preference"]["mean_margin"],
                "unsafe_refusal_rate": d["refusal"]["unsafe_refusal_rate"],
                "benign_refusal_rate": d["refusal"]["benign_refusal_rate"],
                "retention": m_filter.get("retention", ""),
                "harmful_survival_rate": m_filter.get("harmful_survival_rate", ""),
                "clean_retention_rate": m_filter.get("clean_retention_rate", ""),
                "false_rejection_rate": m_filter.get("false_rejection_rate", ""),
                "corruption_detection_f1": m_filter.get("corruption_detection_f1", ""),
            }
        )

    if not rows:
        print(f"[warn] no eval json files in {eval_dir}")
        return

    csv_path = out_dir / "main_results.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"[wrote] {csv_path}  ({len(rows)} rows)")

    # ---- LaTeX Table 1: per (corruption, eta) block, method-rows ----
    tex_path = out_dir / "table1_main.tex"
    with open(tex_path, "w") as f:
        f.write("% auto-generated by aggregate_results.py\n")
        f.write("\\begin{table*}[!t]\n\\centering\n")
        f.write(
            "\\caption{Pilot results on Anthropic HH-RLHF under structured-unsafe corruption. "
            "All rows are the same Qwen2.5-1.5B-Instruct base trained with LoRA-DPO; "
            "the only difference between rows is the filter applied to the training set. "
            "Higher \\textit{preference acc} and \\textit{unsafe refusal} are better; lower "
            "\\textit{harmful survival} and \\textit{benign refusal} are better.}\n"
        )
        f.write("\\label{tab:pilot_main}\n")
        f.write("\\small\n")
        f.write(
            "\\begin{tabular}{l l l r r r r r}\n\\toprule\n"
            "Corruption & $\\eta$ & Method & "
            "Pref Acc $\\uparrow$ & Unsafe Ref. $\\uparrow$ & Benign Ref. $\\downarrow$ & "
            "Retention & Harm. Surv.\\ $\\downarrow$ \\\\ \n\\midrule\n"
        )
        for r in rows:
            ret = f"{float(r['retention'])*100:.1f}\\%" if r['retention'] != "" else "--"
            hs = f"{float(r['harmful_survival_rate'])*100:.2f}\\%" if r['harmful_survival_rate'] != "" else "--"
            f.write(
                f"{r['corruption']} & {r['eta']/100:.2f} & {r['method']} & "
                f"{r['preference_acc']:.3f} & {r['unsafe_refusal_rate']:.3f} & "
                f"{r['benign_refusal_rate']:.3f} & {ret} & {hs} \\\\\n"
            )
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    print(f"[wrote] {tex_path}")


if __name__ == "__main__":
    main()
